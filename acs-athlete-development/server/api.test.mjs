import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApp } from '../server.mjs';
const password='test-only-passphrase-123';
async function harness(t){
  const dir=await mkdtemp(join(tmpdir(),'acs-api-')),filename=join(dir,'acs.sqlite');
  let server,base;
  const start=async()=>{server=createApp({filename});await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));base=`http://127.0.0.1:${server.address().port}`;};
  const stop=()=>new Promise(resolve=>server.close(resolve));
  await start();t.after(async()=>{await stop();await rm(dir,{recursive:true,force:true});});
  const request=async(path,method='GET',data,cookie='',extra={})=>{const response=await fetch(base+path,{method,headers:{Origin:base,'Content-Type':'application/json',Cookie:cookie,...extra},body:data===undefined?undefined:JSON.stringify(data)});return {status:response.status,body:await response.json(),cookie:response.headers.get('set-cookie')?.split(';')[0],headers:response.headers};};
  return {request,restart:async()=>{await stop();await start();}};
}
