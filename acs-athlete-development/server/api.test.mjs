test('sex is validated and persisted; authenticated leaderboards expose only ranking summaries',async t=>{
  const {request:r,restart}=await harness(t);
  assert.equal((await r('/api/leaderboards')).status,401);
  const coach=await r('/api/setup','POST',{email:'coach@example.test',password}),cookie=coach.cookie;
  const data={schemaVersion:1,athletes:[{id:'F1',name:'Girl',level:1,sex:'female'},{id:'M1',name:'Boy',level:1,sex:'male',baselines:[{name:'Private lift',startWeight:30}]},{id:'U1',name:'Not recorded',level:1}],records:[{id:'RF',athleteId:'F1',metric:'bench',value:90,date:'2026-01-01',note:'Private note'},{id:'RM',athleteId:'M1',metric:'bench',value:100,date:'2026-01-02',note:'Private note'},{id:'RU',athleteId:'U1',metric:'bench',value:200}],plans:[],workouts:[]};
  const invalid=structuredClone(data);invalid.athletes[0].sex='invalid';
  assert.equal((await r('/api/workspace','PUT',{revision:0,data:invalid},cookie)).status,400);
  assert.equal((await r('/api/workspace','PUT',{revision:0,data},cookie)).status,200);
  await r('/api/accounts','POST',{email:'athlete@example.test',password,role:'athlete',athleteId:'F1'},cookie);
  const athlete=(await r('/api/login','POST',{email:'athlete@example.test',password})).cookie;
  assert.equal((await r('/api/workspace','PUT',{revision:1,data},athlete)).status,403);
  const rankings=await r('/api/leaderboards','GET',undefined,athlete);
  assert.equal(rankings.status,200);
  const bench=rankings.body.leaderboards.find(b=>b.metricId==='bench');
  assert.deepEqual(bench.girls.map(e=>e.name),['Girl']);assert.deepEqual(bench.boys.map(e=>e.name),['Boy']);
  assert.deepEqual(Object.keys(bench.boys[0]).sort(),['athleteId','date','name','rank','value']);
  assert.ok(!JSON.stringify(rankings.body).includes('Private'));
  const own=(await r('/api/workspace','GET',undefined,athlete)).body.data;
  assert.deepEqual(own.athletes.map(a=>a.id),['F1']);assert.deepEqual(own.records.map(a=>a.id),['RF']);
  await restart();assert.equal((await r('/api/workspace','GET',undefined,cookie)).body.data.athletes[0].sex,'female');
  data.athletes[2].sex='female';
  assert.equal((await r('/api/workspace','PUT',{revision:1,data},cookie)).status,200);
  const updated=(await r('/api/leaderboards','GET',undefined,athlete)).body.leaderboards.find(b=>b.metricId==='bench');
  assert.deepEqual(updated.girls.map(e=>e.name),['Not recorded','Girl']);
  data.athletes[2].sex=null;
  assert.equal((await r('/api/workspace','PUT',{revision:2,data},cookie)).status,200);
  assert.equal((await r('/api/leaderboards','GET',undefined,cookie)).body.leaderboards.find(b=>b.metricId==='bench').girls.length,1);
});
